CREATE TABLE semantic_metric (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR2(100 CHAR) NOT NULL UNIQUE,
    name VARCHAR2(200 CHAR) NOT NULL,
    description VARCHAR2(1000 CHAR),
    expression_sql VARCHAR2(2000 CHAR) NOT NULL,
    base_table VARCHAR2(200 CHAR) NOT NULL,
    status VARCHAR2(30 CHAR) DEFAULT 'DRAFT' NOT NULL,
    version NUMBER(10) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE semantic_relation (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    left_table VARCHAR2(200 CHAR) NOT NULL,
    right_table VARCHAR2(200 CHAR) NOT NULL,
    join_type VARCHAR2(20 CHAR) DEFAULT 'LEFT' NOT NULL,
    join_condition VARCHAR2(1000 CHAR) NOT NULL,
    cardinality VARCHAR2(20 CHAR) NOT NULL,
    enabled NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT ck_semantic_relation_enabled CHECK (enabled IN (0, 1))
);

CREATE TABLE knowledge_document (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name VARCHAR2(500 CHAR) NOT NULL,
    content_type VARCHAR2(200 CHAR),
    storage_path VARCHAR2(1000 CHAR) NOT NULL,
    status VARCHAR2(30 CHAR) NOT NULL,
    index_version VARCHAR2(100 CHAR),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE query_run (
    id VARCHAR2(36 CHAR) PRIMARY KEY,
    question VARCHAR2(2000 CHAR) NOT NULL,
    generated_sql CLOB,
    status VARCHAR2(30 CHAR) NOT NULL,
    answer CLOB,
    error_message VARCHAR2(2000 CHAR),
    elapsed_ms NUMBER(19),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE query_feedback (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query_run_id VARCHAR2(36 CHAR) NOT NULL,
    rating NUMBER(10) NOT NULL,
    feedback_comment VARCHAR2(2000 CHAR),
    corrected_sql CLOB,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE audit_event (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trace_id VARCHAR2(100 CHAR),
    event_type VARCHAR2(100 CHAR) NOT NULL,
    actor VARCHAR2(200 CHAR) NOT NULL,
    resource_type VARCHAR2(100 CHAR),
    resource_id VARCHAR2(200 CHAR),
    detail CLOB,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE report_job (
    id VARCHAR2(36 CHAR) PRIMARY KEY,
    title VARCHAR2(500 CHAR) NOT NULL,
    request_text VARCHAR2(2000 CHAR) NOT NULL,
    status VARCHAR2(30 CHAR) NOT NULL,
    content_json CLOB,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
