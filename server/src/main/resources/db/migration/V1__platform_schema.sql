CREATE TABLE IF NOT EXISTS semantic_metric (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    description VARCHAR(1000),
    expression_sql VARCHAR(2000) NOT NULL,
    base_table VARCHAR(200) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS semantic_relation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    left_table VARCHAR(200) NOT NULL,
    right_table VARCHAR(200) NOT NULL,
    join_type VARCHAR(20) NOT NULL DEFAULT 'LEFT',
    join_condition VARCHAR(1000) NOT NULL,
    cardinality VARCHAR(20) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS knowledge_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name VARCHAR(500) NOT NULL,
    content_type VARCHAR(200),
    storage_path VARCHAR(1000) NOT NULL,
    status VARCHAR(30) NOT NULL,
    index_version VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS query_run (
    id VARCHAR(36) PRIMARY KEY,
    question VARCHAR(2000) NOT NULL,
    generated_sql TEXT,
    status VARCHAR(30) NOT NULL,
    answer TEXT,
    error_message VARCHAR(2000),
    elapsed_ms BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS query_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query_run_id VARCHAR(36) NOT NULL,
    rating INTEGER NOT NULL,
    feedback_comment VARCHAR(2000),
    corrected_sql TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trace_id VARCHAR(100),
    event_type VARCHAR(100) NOT NULL,
    actor VARCHAR(200) NOT NULL,
    resource_type VARCHAR(100),
    resource_id VARCHAR(200),
    detail TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS report_job (
    id VARCHAR(36) PRIMARY KEY,
    title VARCHAR(500) NOT NULL,
    request_text VARCHAR(2000) NOT NULL,
    status VARCHAR(30) NOT NULL,
    content_json TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
